import assert from 'node:assert/strict';
import { buatPemeriksaanPembayaran } from '../dist/lib/pemeriksaan-pembayaran.js';
let waktu = 0, jumlah = 0, selesai;
const periksa = buatPemeriksaanPembayaran(5000, () => waktu);
const pertama = periksa(1, () => { jumlah++; return new Promise(r => { selesai = r; }); });
await Promise.resolve();
assert.strictEqual(periksa(1, () => { throw new Error('TIDAK_BOLEH_DIPANGGIL'); }), pertama);
waktu = 60000;
assert.strictEqual(periksa(1, () => Promise.resolve('SALAH')), pertama, 'Request masih berjalan tidak boleh ditumpuk');
selesai('sah'); assert.equal(await pertama, 'sah');
assert.equal(await periksa(1, () => Promise.resolve('SALAH')), 'sah');
assert.equal(jumlah, 1);
waktu += 5001;
assert.equal(await periksa(1, () => { jumlah++; return Promise.resolve('terbaru'); }), 'terbaru');
assert.equal(jumlah, 2);
assert.equal(await periksa(2, () => Promise.resolve('lain')), 'lain');
let gagal = 0;
await assert.rejects(periksa(3, () => { gagal++; throw new Error('TIMEOUT_MOCK'); }));
await assert.rejects(periksa(3, () => { gagal++; return Promise.resolve('SALAH'); }));
assert.equal(gagal, 1, 'Timeout tidak boleh langsung dipanggil berulang');
waktu += 5001; assert.equal(await periksa(3, () => Promise.resolve('pulih')), 'pulih');
console.log('PASS PAYMENT-CHECK: request concurrent/in-flight digabung, jeda dari selesai, transaksi terpisah, failure cooldown, expiry dan recovery; tanpa DB/provider nyata.');
