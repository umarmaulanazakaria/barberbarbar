import { Router } from "express";
import { ambilPelangganBerdasarkanId, ambilSemuaPelanggan, blokirPelanggan, bukaBlokirPelanggan, tambahPelanggan, ubahPelanggan } from "../controllers/pelanggan.controller.js";
import { hanyaAdmin } from "../middleware/role.middleware.js";
import { statusMembershipOperator } from "../controllers/pelanggan.controller.js";
const routerPelanggan = Router();
routerPelanggan.get("/", ambilSemuaPelanggan);
routerPelanggan.post("/", hanyaAdmin, tambahPelanggan);
routerPelanggan.get("/:id", ambilPelangganBerdasarkanId);
routerPelanggan.get("/:id/membership-status", statusMembershipOperator);
routerPelanggan.patch("/:id", hanyaAdmin, ubahPelanggan);
routerPelanggan.delete("/:id", hanyaAdmin, (_req,res)=>res.status(405).json({pesan:"Penghapusan permanen dinonaktifkan. Gunakan Arsipkan Profil pada Menu Pelanggan."}));
routerPelanggan.patch("/:id/blokir", hanyaAdmin, blokirPelanggan);
routerPelanggan.patch("/:id/buka-blokir", hanyaAdmin, bukaBlokirPelanggan);
export default routerPelanggan;
